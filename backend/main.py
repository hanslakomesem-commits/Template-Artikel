"""ZAIN.NET v10 — normalize browser-composed Word through LibreOffice.

The uploaded DOCX is an intermediate file. The final returned DOCX is ALWAYS
saved by LibreOffice on the server; we intentionally do not offer a browser-
only fallback, because that variant failed on the user's Microsoft Word 2010.
"""
from __future__ import annotations

import asyncio
import io
import os
import shutil
import subprocess
import tempfile
from pathlib import Path
from zipfile import BadZipFile, ZipFile

from fastapi import FastAPI, File, Form, HTTPException, UploadFile
from fastapi.concurrency import run_in_threadpool
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import Response
from lxml import etree

MAX_INPUT_BYTES = int(os.getenv("MAX_DOCX_MB", "25")) * 1024 * 1024
MAX_ZIP_UNCOMPRESSED = 180 * 1024 * 1024
LIBREOFFICE_TIMEOUT = int(os.getenv("LIBREOFFICE_TIMEOUT", "120"))
ALLOWED_JOURNALS = {
    "alhuquq", "elnubuwwah", "enasa", "ghancaran", "iqtishadia", "karsa",
    "kiddo", "mabny", "meyarsa", "nuansa", "panyonara", "perdikan",
    "rabbani", "shafin", "sociale",
}
ORIGINS = [s.strip().rstrip("/") for s in os.getenv(
    "ALLOWED_ORIGINS", "https://hanslakomesem-commits.github.io,http://localhost:8080,http://127.0.0.1:8080"
).split(",") if s.strip()]

app = FastAPI(title="ZAIN.NET DOCX Normalizer", version="10.0.0", docs_url=None, redoc_url=None)
app.add_middleware(
    CORSMiddleware,
    allow_origins=ORIGINS,
    allow_methods=["GET", "POST"],
    allow_headers=["Content-Type"],
)
# LibreOffice conversion is CPU/memory intensive. Serialize jobs per container.
conversion_semaphore = asyncio.Semaphore(1)
XML_PARSER = etree.XMLParser(resolve_entities=False, no_network=True, huge_tree=False)


def docx_stats(raw: bytes) -> dict[str, int]:
    """Reject malformed or implausibly huge Office documents before/after conversion."""
    try:
        with ZipFile(io.BytesIO(raw)) as z:
            members = z.infolist()
            if not members or sum(m.file_size for m in members) > MAX_ZIP_UNCOMPRESSED:
                raise ValueError("Ukuran isi DOCX terlalu besar")
            names = {m.filename for m in members}
            if "word/document.xml" not in names or "[Content_Types].xml" not in names:
                raise ValueError("Bukan file Word DOCX yang lengkap")
            if any(n.lower().endswith("vbaproject.bin") for n in names):
                raise ValueError("DOCX dengan macro tidak diperbolehkan")
            # Parse OOXML. A document generated by JS may be syntactically valid
            # but crash Word 2010; normalization is therefore still required.
            root = etree.fromstring(z.read("word/document.xml"), parser=XML_PARSER)
            ns = {"w": "http://schemas.openxmlformats.org/wordprocessingml/2006/main"}
            notes = int(len(root.xpath(".//w:footnoteReference", namespaces=ns)))
            images = int(len(root.xpath(".//*[local-name()='blip']")))
            paras = int(len(root.xpath(".//w:body/w:p", namespaces=ns)))
            return {"footnotes": notes, "images": images, "paragraphs": paras}
    except (BadZipFile, KeyError, etree.XMLSyntaxError, OSError, ValueError) as exc:
        raise ValueError(f"DOCX tidak valid: {exc}") from exc



def flatten_hyperlink_content_controls(raw: bytes) -> bytes:
    """Work around a specific LO/OOXML bug with <w:sdt> inside hyperlinks.

    Some MABNY samples contain an empty Google Docs-style content control
    immediately after a hyperlink. LibreOffice 7.x can export it with
    mismatched hyperlink closing tags. Flatten only empty controls with tags
    starting `goog_rdk_`; preserve any child runs.
    No general XML recovery or silent dropping of unknown content is done.
    """
    ns = {"w": "http://schemas.openxmlformats.org/wordprocessingml/2006/main"}
    with ZipFile(io.BytesIO(raw)) as source:
        xml = source.read("word/document.xml")
        root = etree.fromstring(xml, parser=XML_PARSER)
        wrapped = [node for node in root.xpath(".//w:sdt", namespaces=ns)
                   if node.xpath("./w:sdtPr/w:tag[starts-with(@w:val, 'goog_rdk_')]", namespaces=ns)
                   and not ''.join(node.itertext()).strip()]
        if not wrapped:
            return raw
        for sdt in wrapped:
            parent = sdt.getparent()
            content = sdt.find("{http://schemas.openxmlformats.org/wordprocessingml/2006/main}sdtContent")
            if parent is None or content is None:
                raise ValueError("Content control tidak dapat dinormalisasi tanpa risiko kehilangan teks")
            index = parent.index(sdt)
            for child in list(content):
                content.remove(child)
                parent.insert(index, child)
                index += 1
            parent.remove(sdt)
        new_xml = etree.tostring(root, encoding="UTF-8", xml_declaration=True)
        buffer = io.BytesIO()
        with ZipFile(buffer, "w") as rebuilt:
            for item in source.infolist():
                rebuilt.writestr(item, new_xml if item.filename == "word/document.xml" else source.read(item.filename))
        return buffer.getvalue()


def save_with_libreoffice(raw: bytes) -> bytes:
    """Normalize using a unique LibreOffice profile, isolated per request."""
    source_stats = docx_stats(raw)
    # Keep the original student text; remove only a known non-visual hyperlink
    # content-control wrapper that LibreOffice otherwise exports incorrectly.
    raw = flatten_hyperlink_content_controls(raw)
    assert docx_stats(raw)["footnotes"] == source_stats["footnotes"]
    exe = shutil.which("libreoffice") or shutil.which("soffice")
    if not exe:
        raise RuntimeError("LibreOffice tidak terpasang di server")
    with tempfile.TemporaryDirectory(prefix="zainnet_", dir="/tmp") as tmp:
        root = Path(tmp)
        source = root / "source"
        dest = root / "converted"
        source.mkdir()
        dest.mkdir()
        incoming = source / "zainnet_intermediate.docx"
        incoming.write_bytes(raw)
        profile = (root / "lo_profile").as_uri()
        cmd = [
            exe,
            f"-env:UserInstallation={profile}",
            "--headless", "--convert-to", "docx:Office Open XML Text",
            "--outdir", str(dest), str(incoming),
        ]
        try:
            result = subprocess.run(
                cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                timeout=LIBREOFFICE_TIMEOUT, check=False,
                env={**os.environ, "SAL_USE_VCLPLUGIN": "svp", "HOME": str(root), "DISPLAY": ""},
            )
        except subprocess.TimeoutExpired as exc:
            raise RuntimeError("LibreOffice melewati batas waktu pemrosesan") from exc
        output = dest / incoming.name
        if result.returncode != 0 or not output.is_file() or output.stat().st_size < 1000:
            # No user content in logs or error response.
            raise RuntimeError("LibreOffice tidak berhasil menyimpan ulang DOCX")
        normalized = output.read_bytes()
        out_stats = docx_stats(normalized)
        # A disappearing footnote is data loss, not successful formatting.
        if out_stats["footnotes"] < source_stats["footnotes"]:
            raise RuntimeError("Validasi gagal: catatan kaki hilang setelah konversi")
        if source_stats["images"] and not out_stats["images"]:
            raise RuntimeError("Validasi gagal: semua gambar hilang setelah konversi")
        return normalized


@app.get("/api/health")
def health():
    return {"status": "ok" if (shutil.which("libreoffice") or shutil.which("soffice")) else "missing_libreoffice",
            "service": "ZAIN.NET DOCX Normalizer", "version": "10.0"}


@app.post("/api/normalize")
async def normalize(file: UploadFile = File(...), template_id: str = Form(...)):
    if template_id.lower() not in ALLOWED_JOURNALS:
        raise HTTPException(422, "Template jurnal tidak dikenali")
    if not file.filename or not file.filename.lower().endswith(".docx"):
        raise HTTPException(422, "Hanya DOCX yang dapat diproses")
    raw = await file.read(MAX_INPUT_BYTES + 1)
    await file.close()
    if not raw or len(raw) > MAX_INPUT_BYTES:
        raise HTTPException(413, "DOCX kosong atau melebihi batas ukuran")
    try:
        docx_stats(raw)
    except ValueError as exc:
        raise HTTPException(422, str(exc)) from exc
    try:
        async with conversion_semaphore:
            normalized = await run_in_threadpool(save_with_libreoffice, raw)
    except RuntimeError as exc:
        raise HTTPException(422, str(exc)) from exc
    # Never return un-normalized fallback.
    return Response(
        content=normalized,
        media_type="application/vnd.openxmlformats-officedocument.wordprocessingml.document",
        headers={"Content-Disposition": 'attachment; filename="ZAINNET_WORD2010_LO.docx"',
                 "Cache-Control": "no-store", "X-Content-Type-Options": "nosniff"},
    )
